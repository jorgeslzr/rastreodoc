create extension if not exists pgcrypto;
create extension if not exists citext;

do $$
begin
  create type public.document_status as enum (
    'EN_OFICINA',
    'ENVIADO',
    'AUTORIZADO',
    'RECHAZADO',
    'REENVIADO'
  );
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create type public.app_role as enum ('admin', 'supervisor', 'empleado', 'consulta');
exception
  when duplicate_object then null;
end
$$;


create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username citext not null unique check (length(trim(username::text)) >= 3),
  role public.app_role not null default 'consulta',
  created_at timestamptz not null default now()
);

create table if not exists public.agencies (
  id uuid primary key default gen_random_uuid(),
  name citext not null unique check (length(trim(name::text)) > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.document_types (
  id uuid primary key default gen_random_uuid(),
  name citext not null unique check (length(trim(name::text)) > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.lawyers (
  id uuid primary key default gen_random_uuid(),
  name citext not null unique check (length(trim(name::text)) > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.auxiliaries (
  id uuid primary key default gen_random_uuid(),
  name citext not null unique check (length(trim(name::text)) > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.municipalities (
  id uuid primary key default gen_random_uuid(),
  name citext not null unique check (length(trim(name::text)) > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.case_files (
  id uuid primary key default gen_random_uuid(),
  number citext not null unique check (length(trim(number::text)) > 0),
  auxiliary text check (auxiliary is null or length(trim(auxiliary)) between 1 and 120),
  created_at timestamptz not null default now()
);

create table if not exists public.documents (
  id uuid primary key default gen_random_uuid(),
  case_file_id uuid not null references public.case_files(id) on delete restrict,
  document_type_id uuid not null references public.document_types(id) on delete restrict,
  agency_id uuid not null references public.agencies(id) on delete restrict,
  lawyer_id uuid references public.lawyers(id) on delete restrict,
  auxiliary_id uuid references public.auxiliaries(id) on delete restrict,
  label text,
  folio_forma text,
  municipality text,
  cadastral_file_number text,
  deed_entries jsonb not null default '[]'::jsonb,
  status public.document_status not null default 'EN_OFICINA',
  qr_token uuid not null unique default gen_random_uuid(),
  last_movement_at timestamptz not null default now(),
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  constraint document_label_length check (
    label is null or length(label) <= 120
  ),
  constraint document_deed_fields_length check (
    (folio_forma is null or length(folio_forma) <= 120)
    and (municipality is null or length(municipality) <= 120)
    and (cadastral_file_number is null or length(cadastral_file_number) <= 120)
  ),
  constraint documents_deed_entries_array check (jsonb_typeof(deed_entries) = 'array')
);

create index if not exists documents_case_file_id_idx on public.documents(case_file_id);
create index if not exists documents_auxiliary_id_idx on public.documents(auxiliary_id);
create index if not exists documents_status_idx on public.documents(status);
create index if not exists documents_agency_id_idx on public.documents(agency_id);

create table if not exists public.movements (
  id bigint generated by default as identity primary key,
  document_id uuid not null references public.documents(id) on delete restrict,
  status public.document_status not null,
  occurred_at timestamptz not null default now(),
  rejection_reason text,
  receipt_number text,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  constraint rejection_reason_length check (
    rejection_reason is null or length(rejection_reason) <= 250
  ),
  constraint receipt_number_length check (
    receipt_number is null or length(receipt_number) <= 100
  )
);

create index if not exists movements_document_date_idx
  on public.movements(document_id, occurred_at desc);

